def edit(path, pairs, tail=None):
    s = open(path, encoding='utf8').read()
    for old, new in pairs:
        assert old in s, (path, old[:80])
        s = s.replace(old, new)
    if tail:
        s = tail(s)
    open(path, 'w', encoding='utf8').write(s)

